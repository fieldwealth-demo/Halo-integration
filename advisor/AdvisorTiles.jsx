function TileInfo({ title }) {
  const info = TILE_INFO[title];
  const [open, setOpen] = React.useState(false);
  const [pos, setPos] = React.useState({ top:0, left:0 });
  const wrapRef = React.useRef();
  const btnRef = React.useRef();
  const POP_W = 300;
  const place = React.useCallback(() => {
    const el = btnRef.current;
    if (!el) return;
    const r = el.getBoundingClientRect();
    const margin = 12;
    let left = r.left - 6;
    left = Math.min(left, window.innerWidth - POP_W - margin);
    left = Math.max(margin, left);
    setPos({ top: r.bottom + 8, left, arrow: r.left + r.width/2 - left });
  }, []);
  React.useEffect(() => {
    if (!open) return;
    place();
    const onDoc = (e) => { if (wrapRef.current && !wrapRef.current.contains(e.target)) setOpen(false); };
    const onKey = (e) => { if (e.key === 'Escape') setOpen(false); };
    const onReflow = () => place();
    document.addEventListener('mousedown', onDoc);
    document.addEventListener('keydown', onKey);
    window.addEventListener('resize', onReflow);
    window.addEventListener('scroll', onReflow, true);
    return () => {
      document.removeEventListener('mousedown', onDoc);
      document.removeEventListener('keydown', onKey);
      window.removeEventListener('resize', onReflow);
      window.removeEventListener('scroll', onReflow, true);
    };
  }, [open, place]);
  if (!info) return null;
  const Row = ({ icon, label, text, color }) => (
    <div style={{ display:'flex', gap:10, padding:'10px 0', borderTop:'1px solid rgba(75,85,99,0.4)' }}>
      <span style={{ flex:'0 0 auto', width:22, height:22, borderRadius:6, background:'rgba(255,255,255,0.05)', display:'inline-flex', alignItems:'center', justifyContent:'center', color }}>
        <i className={`fa-solid ${icon}`} style={{ width:12, height:12 }} />
      </span>
      <div style={{ minWidth:0 }}>
        <div style={{ fontFamily:'Inter', fontSize:10.5, fontWeight:600, letterSpacing:0.5, textTransform:'uppercase', color:'rgb(140,140,140)', marginBottom:3 }}>{label}</div>
        <div style={{ fontFamily:'Inter', fontSize:12.5, lineHeight:1.5, color:'rgb(209,213,219)' }}>{text}</div>
      </div>
    </div>
  );
  return (
    <span ref={wrapRef} style={{ display:'inline-flex', marginLeft:7 }} onMouseDown={(e)=>e.stopPropagation()}>
      <button
        ref={btnRef}
        className="tile-info-btn"
        aria-label={`How “${title}” is calculated`}
        aria-haspopup="dialog"
        aria-expanded={open}
        onClick={(e)=>{ e.stopPropagation(); setOpen(o=>!o); }}
        style={{
          background:'transparent', border:'none', cursor:'pointer', padding:0,
          width:18, height:18, borderRadius:9, display:'inline-flex', alignItems:'center', justifyContent:'center',
          color: open ? 'rgb(94,214,164)' : 'rgb(120,124,130)', transition:'color 120ms ease',
        }}
      >
        <i className="fa-solid fa-circle-info" style={{ width:14, height:14 }} />
      </button>
      {open && ReactDOM.createPortal((
        <div role="dialog" aria-label={`${title} — data source`} onMouseDown={(e)=>e.stopPropagation()} style={{
          position:'fixed', top:pos.top, left:pos.left, zIndex:9000, width:POP_W, boxSizing:'border-box',
          background:'rgb(28,30,34)', border:'1px solid rgb(75,85,99)', borderRadius:12,
          boxShadow:'0 16px 40px -8px rgba(0,0,0,0.6)', padding:'12px 14px 4px', cursor:'default',
        }}>
          <div style={{
            position:'absolute', top:-6, left:Math.max(8, Math.min((pos.arrow||14)-5, POP_W-18)), width:10, height:10, background:'rgb(28,30,34)',
            borderLeft:'1px solid rgb(75,85,99)', borderTop:'1px solid rgb(75,85,99)', transform:'rotate(45deg)',
          }} />
          <div style={{ fontFamily:'Inter', fontSize:13, fontWeight:600, color:'rgb(249,250,251)', paddingBottom:8 }}>{title}</div>
          <Row icon="fa-database" label="Data source" text={info.source} color="rgb(125,178,255)" />
          {info.method && <Row icon="fa-function" label="How it's calculated" text={info.method} color="rgb(94,214,164)" />}
          {info.cadence && <Row icon="fa-clock-3" label="Refresh cadence" text={info.cadence} color="rgb(196,181,253)" />}
        </div>
      ), document.body)}
    </span>
  );
}

function Tile({ title, children, onMore, style, footLabel }) {
  const ref = React.useRef();
  const period = React.useContext(PeriodContext);
  const label = footLabel || periodToLabel(period);
  const handleMore = () => {
    if (typeof onMore === 'function') onMore();
    else window.dispatchEvent(new CustomEvent('tile:see-more', { detail: { title } }));
  };
  return (
    <div ref={ref} style={{ ...TILE, ...style }}>
      <div style={TILE_HEAD}>
        <div style={TILE_TITLE}>{title}</div>
        <TileInfo title={title} />
        <button className="tile-overflow-btn" style={{ ...OVERFLOW, marginLeft:'auto' }} aria-label="More"><i className="fa-solid fa-ellipsis" style={{ width:14, height:14 }} /></button>
      </div>
      <div style={TILE_BODY}>{children}</div>
      <div style={TILE_FOOT}>
        <span>{label}</span>
        <a style={SEE_MORE} onClick={handleMore}>See more <i className="fa-solid fa-chevron-right" style={{ width:12, height:12 }} /></a>
      </div>
    </div>
  );
}

