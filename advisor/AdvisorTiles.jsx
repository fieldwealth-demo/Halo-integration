function periodToLabel(period) {
  switch (period) {
    case 'Today':           return 'Today · May 13';
    case 'This week':       return 'May 7 – 13';
    case 'This month':      return 'May 1 – 13';
    case 'This quarter':    return 'Apr – May';
    case 'Year to date':    return 'Jan – May';
    case 'Last 12 months':  return 'Jun \u201925 – May \u201926';
    case 'All time':        return 'All time';
    default:                return period || 'As of Today';
  }
}
window.periodToLabel = periodToLabel;

